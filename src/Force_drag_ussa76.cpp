void Force_drag_ussa76::compute_acceleration()
{
    // Report error, this displays the issue to the user and halts simulation
    if (state->geodetic.alt < 100.0) {
        std::stringstream error;
        error.precision(16);
        error << "Force_drag: Altitude too low, " << state->geodetic.alt
              << " km.";
        state->errors.push_back(error.str());
    }

    // USSA up to 1000 km, with exponential decay function above
    double rho = ussa1976_density(state->geodetic.alt);
    state->atmos_density = rho;

    //std::cout << "Altitude (km): " <<  state->geodetic.alt << std::endl;
    //std::cout << "Latitude: " << state->geodetic.lat << std::endl;
    //std::cout << "Longitude: " << state->geodetic.lon << std::endl;
    //std::cout << "Density: " << rho << "kg/m^3" <<  std::endl;

    // Method that uses a fit to JB2008 values 
    // std::cout << "Density: " << rho << "kg/m^3" <<  std::endl;
    // state->atmos_density = get_density(state->geodetic.alt);

    // space-craft acceleration in km/s^2 in ECEF frame
    a_ecef = minus500C_dAm * rho * state->ecef_v * state->ecef_rso_vel;

    //std::cout << "minus500C_dAm: " << minus500C_dAm << std::endl;    
    
    // std::cout << "Acceleration: " << state->a_ecef << "km/s^2" << std::endl;
    
    //a_ecef.print();
   
    state->total_a_ecef += a_ecef;
   
}

double Force_drag_ussa76::ussa1976_density(double alt)
{
    double rho;

    if (alt < 0.0) {
        rho = ussa1976_density_array[0];
    } else if (alt < 1000.0) {
        double hectometers = alt * 10.0; // Altitute in hm, 1 hm = 0.1 km
        double lower_bound_d = std::floor(hectometers);

        size_t lower_bound = static_cast<size_t>(lower_bound_d);

        double y1 = ussa1976_density_array[lower_bound];
        double y2 = ussa1976_density_array[lower_bound + 1];

        rho = ((y2 - y1) * (hectometers - lower_bound_d) + y1);
    } else {
        rho = (35.57477 + 1.389 * std::exp(alt / -288.2)) * 1E-16;
    }
   
    return rho;
}

