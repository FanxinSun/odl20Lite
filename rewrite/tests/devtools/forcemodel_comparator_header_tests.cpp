    "// harmonic polynomial q, whose potential is GM a_e^n N_nm q / r^(2n+1), with N_nm and the registered bound's Phi_nm.  Each monomial\n"
    "// coefficient is a dyadic rational, exact in a double; N_nm is printed to 24 digits for a long double.\n"
    "#pragma once\n"
    "\n"
    "namespace odl::forcemodel::comparator {\n"
    "\n"
    "struct Monomial { int i, j, k; double c; };\n"
    "struct Harmonic {\n"
    "    int n, m;\n"
    "    char kind;                 ///< 'C' or 'S'\n"
    "    long double norm;          ///< N_nm, TN36-6 (6.2b)\n"
    "    double phi;                ///< Lemma 2's Phi_nm (tools/forcemodel_fd_sizing.cpp)\n"
    "    const Monomial* q;\n"
    "    int terms;\n"
    "};\n"
    "\n";

