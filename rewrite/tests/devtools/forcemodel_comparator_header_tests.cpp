// of an exact rational and what is refused, the header of degree 2 written out by hand, the header's shape for the other degrees, the refusal of a coefficient that no double holds, the tool's command line
// and what it does to a file, and the real tree.  (ctests `forcemodel_comparator_header.behaviour` and `forcemodel_comparator_header.real_tree`; the Python tool had no test of its own.)
//
// Every expectation is DERIVED BY HAND, from the solid polynomials of degree 2 (worked out in gradient_reference_tests.cpp), the norms N_nm (evaluated with GNU bc, a host tool used to derive digits and
// never by the build) and the f-strings of forcemodel_comparator_header.py, and not taken from running the port.  The hexadecimal Phi of the five coefficients of degree 2 are the Python tool's, as the
// committed header holds them; every one of them is also recomputed in forcemodel_fd_sizing_tests.cpp from hand-derived closed forms.

